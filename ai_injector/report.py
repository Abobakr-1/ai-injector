"""Report generation: Markdown and JSON.

The report is written to be *honest*: it leads with demonstrated findings, keeps
INCONCLUSIVE separate, records negative controls, lists untested/error surfaces
as coverage gaps, and never upgrades a verdict. A run with zero CONFIRMED
results is a valid, useful report.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

from .evidence import Finding, utc_stamp
from .verdicts import Verdict

_SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "informational": 4}


def _sorted_findings(findings: List[Finding]) -> List[Finding]:
    def key(f: Finding):
        return (
            0 if f.verdict == Verdict.CONFIRMED.value else 1,
            _SEV_ORDER.get(f.severity, 9),
            f.index,
        )

    return sorted(findings, key=key)


def render_markdown(
    *,
    target_name: str,
    target_url: str,
    adapter: str,
    module: str,
    findings: List[Finding],
    run_id: str = "",
    extra_notes: str = "",
) -> str:
    counts: Dict[str, int] = {v.value: 0 for v in Verdict}
    for f in findings:
        counts[f.verdict] = counts.get(f.verdict, 0) + 1

    lines: List[str] = []
    lines.append(f"# ai-injector report — {module} injection")
    lines.append("")
    lines.append(f"- **Target:** `{target_name}` ({target_url})")
    lines.append(f"- **Adapter:** `{adapter}`")
    lines.append(f"- **Module:** `{module}`")
    if run_id:
        lines.append(f"- **Run:** `{run_id}`")
    lines.append(f"- **Generated:** {utc_timestamp()}")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Verdict | Count |")
    lines.append("| --- | --- |")
    for v in Verdict:
        lines.append(f"| {v.value} | {counts.get(v.value, 0)} |")
    lines.append("")
    lines.append(
        "> Verdicts: **CONFIRMED** = a deterministic oracle fired (a derived canary "
        "that cannot be produced by echoing the prompt). **INCONCLUSIVE** = a weak "
        "signal only; needs manual review. **NEGATIVE** = payload delivered, no "
        "signal, controls healthy. **ERROR** = transport/protocol failure (a "
        "coverage gap, not a negative). **BLOCKED** = not executed (dry run/scope)."
    )
    lines.append("")

    confirmed = [f for f in findings if f.verdict == Verdict.CONFIRMED.value]
    inconclusive = [f for f in findings if f.verdict == Verdict.INCONCLUSIVE.value]
    errors = [f for f in findings if f.verdict == Verdict.ERROR.value]
    negatives = [f for f in findings if f.verdict == Verdict.NEGATIVE.value]
    blocked = [f for f in findings if f.verdict == Verdict.BLOCKED.value]

    lines.append("## Confirmed findings")
    lines.append("")
    if not confirmed:
        lines.append("_None. No injection produced a deterministic success signal "
                     "under the tested conditions._")
        lines.append("")
    for f in _sorted_findings(confirmed):
        lines.extend(_finding_block(f))
        lines.append("")

    lines.append("## Inconclusive (needs review)")
    lines.append("")
    if not inconclusive:
        lines.append("_None._")
        lines.append("")
    for f in _sorted_findings(inconclusive):
        lines.extend(_finding_block(f, brief=True))
        lines.append("")

    if errors:
        lines.append("## Coverage gaps (errors — NOT negatives)")
        lines.append("")
        for f in errors:
            lines.append(f"- `{f.finding_id}` {f.payload_id}: {f.detail}")
        lines.append("")

    if blocked:
        lines.append("## Not executed")
        lines.append("")
        for f in blocked:
            lines.append(f"- `{f.finding_id}` {f.payload_id}: {f.detail}")
        lines.append("")

    lines.append("## Negative results (tested, no signal)")
    lines.append("")
    lines.append(f"{len(negatives)} payload(s) were delivered with healthy controls "
                 "and produced no compliance signal.")
    lines.append("")
    for f in negatives:
        lines.append(f"- `{f.finding_id}` {f.payload_id} [{f.technique}]")
    lines.append("")

    lines.append("## Coverage & limitations")
    lines.append("")
    lines.append(
        "- Payloads are a finite sample; a negative means \"no signal under these "
        "tested conditions\", not \"the target is secure\"."
    )
    lines.append(
        "- Detection is canary-first (deterministic) with rule-based weak signals. "
        "Semantic jailbreaks without a canary can only reach INCONCLUSIVE."
    )
    lines.append(
        "- ERROR entries indicate surfaces that were not validly tested."
    )
    if extra_notes:
        lines.append("")
        lines.append(extra_notes)

    lines.append("")
    lines.append("---")
    lines.append("_Generated by ai-injector. Authorized testing only._")
    lines.append("")
    return "\n".join(lines)


def _finding_block(f: Finding, brief: bool = False) -> List[str]:
    out: List[str] = []
    out.append(f"### {f.finding_id} — `{f.payload_id}`")
    out.append("")
    out.append(f"- **Technique:** {f.technique}")
    out.append(f"- **Verdict:** {f.verdict} (oracle: {f.oracle})")
    out.append(f"- **Severity if exploited:** {f.severity}")
    out.append(f"- **Detail:** {f.detail}")
    if f.matched:
        out.append(f"- **Matched:** `{'`, `'.join(f.matched[:4])}`")
    if f.evidence_file:
        out.append(f"- **Evidence:** `{f.evidence_file}`")
    out.append("")
    if not brief:
        out.append("**Request (payload):**")
        out.append("")
        out.append("```text")
        out.append((f.request_text or "").strip()[:1500])
        out.append("```")
        out.append("")
        out.append("**Response (excerpt):**")
        out.append("")
        out.append("```text")
        out.append((f.response_text or "").strip()[:1500])
        out.append("```")
    return out


def render_json(
    *,
    target_name: str,
    target_url: str,
    adapter: str,
    module: str,
    findings: List[Finding],
    run_id: str = "",
) -> str:
    counts: Dict[str, int] = {v.value: 0 for v in Verdict}
    for f in findings:
        counts[f.verdict] = counts.get(f.verdict, 0) + 1
    payload = {
        "tool": "ai-injector",
        "target": {"name": target_name, "url": target_url, "adapter": adapter},
        "module": module,
        "run_id": run_id,
        "generated": utc_timestamp(),
        "summary": counts,
        "findings": [f.to_dict() for f in _sorted_findings(findings)],
    }
    return json.dumps(payload, indent=2)


def utc_timestamp() -> str:
    return utc_stamp()


def write_report(
    out_dir: Path,
    *,
    fmt: str,
    **kwargs: Any,
) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    if fmt == "json":
        content = render_json(**kwargs)
        path = out_dir / "report.json"
    else:
        content = render_markdown(**kwargs)
        path = out_dir / "report.md"
    path.write_text(content, encoding="utf-8")
    return path
